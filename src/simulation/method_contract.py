"""Locked P08 learner, label-strategy, and cost-sensitive design.

The protocol separates five distinct objects:

1. latent truth generated by the simulation DGP;
2. feasible observed labels and verification;
3. label/observation strategy;
4. predictive learner;
5. training and evaluation cost regimes.

Cost-sensitive learning changes training weights. Cost-sensitive evaluation
changes decision thresholds, classification cost, and budget-constrained
review utility. Neither is allowed to use latent truth during training or
threshold selection.
"""

