def _predictive_method(
    *,
    strategy_id: str,
    learner_id: str,
    learner: Mapping[str, object],
    learner_tier: str,
    training_cost_regime_id: str,
    imbalance_treatment_id: str,
    required_metrics: list[str],
) -> dict[str, object]:
    base_id = f"{strategy_id}__{learner_id}"
    if imbalance_treatment_id != "none":
        base_id += f"__imbalance_{imbalance_treatment_id}"
    return {
        METHOD_ID: f"{base_id}__traincost_{training_cost_regime_id}",
        LABEL_STRATEGY_ID: strategy_id,
        LEARNER_ID: learner_id,
        LEARNER_TIER: learner_tier,
        TRAINING_COST_REGIME_ID: training_cost_regime_id,
        IMBALANCE_TREATMENT_ID: imbalance_treatment_id,
        METHOD_FAMILY: "predictive",
        "strategy": dict(LABEL_STRATEGIES[strategy_id]),
        "learner": dict(learner),
        "imbalance_treatment": dict(IMBALANCE_TREATMENTS[imbalance_treatment_id]),
        "cost_sensitive_training": training_cost_regime_id != "symmetric",
        REQUIRED_METRICS: list(required_metrics),
        EVALUATION_TARGETS: list(PREDICTIVE_EVALUATION_TARGETS),
    }

def _registered_ids(value: object, context: str, allowed: set[str]) -> list[str]:
    values = _string_sequence(value, context)
    unknown = sorted(set(values) - allowed)
    if unknown:
        raise ValueError(f"{context}: unknown ids={unknown}")
    return values


def _registered_id(value: object, context: str, allowed: set[str]) -> str:
    item = str(value or "")
    if item not in allowed:
        raise ValueError(f"{context}: registered id required")
    return item


def _string_sequence(value: object, context: str) -> list[str]:
    if not isinstance(value, list) or not value:
        raise ValueError(f"{context}: nonempty list required")
    values = [str(item) for item in cast(Sequence[object], value)]
    if any(not item for item in values) or len(values) != len(set(values)):
        raise ValueError(f"{context}: unique nonempty strings required")
    return values
